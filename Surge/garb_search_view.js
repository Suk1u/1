    'i.select();try{document.execCommand("copy")}catch(e){}document.body.removeChild(i)}toast("已复制 "+t)}',
    'function norm1(x){',
    '  if(!Array.isArray(x))return x;',
    '  return {garb_id:x[0],name:x[1],title:x[1],large:x[2],images:x[2]?[x[2]]:[],',
    '          status:x[3]?"owned":"catalog",image_id:x[4]||0,goods_type:x[5]};',
    '}',
    'function load(u){return fetch(u+"?"+Date.now()).then(function(r){if(!r.ok)throw 0;return r.json()})',
    '.then(function(d){return (d.items||[]).map(norm1)})}',
    'function boot(){',
    '  var jobs=[];',
    '  if(CFG.catalog)jobs.push(load(CFG.catalog).catch(function(){return[]}));',
    '  if(CFG.themes)jobs.push(load(CFG.themes).catch(function(){return[]}));',
    '  Promise.all(jobs).then(function(res){',
    '    ALL=[];res.forEach(function(a){(a||[]).forEach(function(x){ALL.push(x)})});',
    '    document.getElementById("stat").textContent="库里有 "+ALL.length+" 条，输入名字开始搜";',
    '    if(!ALL.length)document.getElementById("list").innerHTML=',
    '      \'<div class="empty">库是空的<br><br>先跑 <code>index_build.py export --themes</code></div>\';',
