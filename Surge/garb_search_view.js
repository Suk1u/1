    '  var g=document.getElementById("mg"),d=document.getElementById("md");',
    '  if(imgs.length){',
    '    g.innerHTML=imgs.map(function(u){return \'<img src="\'+esc(u)+\'" alt="">\'}).join("");',
    '    d.innerHTML=imgs.map(function(_,i){return \'<i\'+(i===0?\' class="on"\':\'\')+\'></i>\'}).join("");',
    '    g.onscroll=function(){var n=Math.round(g.scrollLeft/g.clientWidth);',
    '      [].forEach.call(d.children,function(e,i){e.className=(i===n?"on":"")})};',
    '  }else{g.innerHTML=\'<div style="padding:60px;text-align:center;color:#39404f;width:100%">无图</div>\';d.innerHTML=""}',
    '  var canUse = (x.status==="owned"||x.status==="onsale"||x.status==="soldout"||x.status==="gone") && x.image_id;',
    '  var rows=[["状态",x.status||x.kind||"-"],',
    '            ["item_id",x.garb_id],',
    '            ["garb_id",x.image_id||"（未知）"],',
    '            ["能否应用",canUse?"可以（点 dress）":"不行 —— 缺 garb_id"]];',
    '  if(x.fans_number)rows.push(["持有编号",x.fans_number]);',
    '  if(x.color_mode)rows.push(["配色模式",x.color_mode]);',
    '  if(x.package_url)rows.push(["主题包",x.package_url]);',
    '  document.getElementById("mkv").innerHTML=rows.map(function(r){',
    '    return \'<div><b>\'+esc(r[0])+\'</b><span>\'+esc(r[1])+\'</span></div>\'}).join("");',
