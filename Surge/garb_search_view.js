    '    document.getElementById("list").innerHTML=\'<div class="empty">拉不到目录<br><br>\'+esc(String(e))+\'</div>\';',
    '  });',
    '}',
    'function tagOf(x){',
    '  if(x.kind==="theme")return \'<span class="tag t-theme">皮肤</span>\';',
