    '      \'<div class="nm">\'+esc(x.name||x.title)+\'</div>\'+',
    '      \'<div class="ids">\'+tagOf(x)+\'<b>\'+x.garb_id+\'</b> / \'+x.image_id+\'</div>\'+',
    '      \'<div class="ids" style="color:#5c667a;margin-top:4px">点开看大图</div></div></div>\';',
    '  }).join("");',
    '}',
