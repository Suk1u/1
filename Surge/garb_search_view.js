    '  var hits=ALL.filter(function(x){return norm(x.name).indexOf(nq)>=0||',
    '    norm(x.title).indexOf(nq)>=0||String(x.garb_id).indexOf(Q)>=0});',
    '  hits.sort(function(a,b){return (norm(a.name)!==nq)-(norm(b.name)!==nq)});',
    '  cnt.textContent="("+hits.length+")";',
    '  if(!hits.length){box.innerHTML=\'<div class="empty">没搜到「\'+esc(Q)+\'」<br><br>换个更短的关键词</div>\';return}',
    '  box.innerHTML=hits.map(function(x,i){',
    '    var img=x.large?\'<img loading="lazy" src="\'+esc(x.large)+\'" alt="">\':\'<div class="noimg">无图</div>\';',
