    '  if(x.status==="gone")return \'<span class="tag t-gone">已移除</span>\';',
    '  if(x.status==="soldout")return \'<span class="tag t-soldout">售罄</span>\';',
    '  if(x.status==="onsale")return \'<span class="tag t-onsale">在售</span>\';',
    '  if(x.status==="catalog")return \'<span class="tag t-cat">未拥有</span>\';',
    '  return "";',
    '}',
    'function render(){',
    '  var box=document.getElementById("list"),cnt=document.getElementById("cnt");',
    '  if(!Q){box.innerHTML="";cnt.textContent="";return}',
